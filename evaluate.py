"""Reproducible SYNTHETIC evaluation. Results describe synthetic data only, not real-world effectiveness.
Usage: python scripts/evaluate.py [--seed 7]"""
import argparse, random, sys, tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from backend import engine as eng
ap = argparse.ArgumentParser(); ap.add_argument("--seed", type=int, default=7); a = ap.parse_args(); rng = random.Random(a.seed)
cfg = {"medium": 30, "high": 60, "critical": 85, "baseline_min_events": 30, "time_window_hours": 4}
def normal(): return dict(hour=rng.gauss(10, 1.3) % 24, failed=int(rng.random() < .1), device_known=True, network_known=True, success=True, mfa=False)
def attack():
    k = rng.choice(["unknown_device", "brute", "night", "multi"])
    e = normal()
    if k == "unknown_device": e["device_known"] = False; e["hour"] = rng.uniform(0, 24)
    if k == "brute": e["failed"] = rng.randint(4, 12)
    if k == "night": e["hour"] = rng.uniform(0, 5); e["device_known"] = rng.random() < .5
    if k == "multi": e.update(device_known=False, network_known=False, hour=rng.uniform(0, 5), failed=rng.randint(2, 8))
    return e
train = [normal() for _ in range(300)]
det = eng.Detector(Path(tempfile.mkdtemp()) / "m.joblib")
det.train([eng.vec(e["hour"], e["failed"], e["device_known"], e["network_known"], e["success"]) for e in train], 30)
hrs = [e["hour"] for e in train]; base = {"n": len(train), "mean_hour": eng.circ_mean(hrs)}
test = [(normal(), 0) for _ in range(400)] + [(attack(), 1) for _ in range(100)]
tp = fp = tn = fn = 0
for e, y in test:
    pred = eng.assess(e, base, det, cfg)["score"] >= cfg["medium"]
    tp += pred and y; fp += pred and not y; tn += (not pred) and not y; fn += (not pred) and y
P = tp / (tp + fp) if tp + fp else 0; R = tp / (tp + fn) if tp + fn else 0; F = 2 * P * R / (P + R) if P + R else 0
print(f"SYNTHETIC evaluation (seed={a.seed}, 300 normal train, 400 normal + 100 attack test, flag = score >= {cfg['medium']})")
print(f"Confusion matrix  TP={tp} FP={fp} TN={tn} FN={fn}")
print(f"Precision={P:.3f} Recall={R:.3f} F1={F:.3f} FalsePositiveRate={fp / (fp + tn):.3f}")
print("Caveat: attack patterns are generated by the same rules the detector uses, so these numbers are optimistic and prove nothing about real telemetry.")
